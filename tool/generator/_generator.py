#!/usr/bin/env python3

import json
from pathlib import Path
from argparse import ArgumentParser

import _state as state
from constants_gen import *
from enums_gen import *
from flags_gen import *
from structs_gen import *
from objects_gen import *
from functions_gen import *
from callbacks_gen import *
from types_gen import *

SKIP_GENERATION = {
  'string view',
  'device.set logging callback',
  'INTERNAL_HAVE_EMDAWNWEBGPU_HEADER',
}

STRUCT_WITH_OUT_VIEWS = {'limits': 'supported limits'}


def handle_struct_with_out_view(name: str):
  out_struct = parse_struct_decl(name)
  out_struct.name = STRUCT_WITH_OUT_VIEWS[name]
  out_struct.is_derived = True
  for member in out_struct.members:
    member.type.default = None

  state.STRUCTS[out_struct.name] = out_struct
  state.STRUCTS[name].out_name = out_struct.name


def parse() -> None:
  for name in state.spec:
    decl = state.spec[name]
    if 'category' in decl:
      category = decl['category']
      if category == 'constant': state.CONSTANTS[name] = parse_constant_decl(name)
      elif category == 'enum': state.ENUMS[name] = parse_enum_decl(name)
      elif category == 'bitmask': state.FLAGS[name] = parse_flag_decl(name)
      elif category == 'structure':
        state.STRUCTS[name] = parse_struct_decl(name)
        if name in STRUCT_WITH_OUT_VIEWS: handle_struct_with_out_view(name)
      elif category == 'object': state.OBJECTS[name] = parse_object_decl(name)
      elif category == 'function': state.GLOBAL_FUNCTIONS[name] = parse_function_decl(decl, name=name)
      elif category == 'callback function': state.CALLBACKS[name] = parse_callback_decl(name)

  print(f'discovered:')
  print(f'  constants: {len(state.CONSTANTS)}')
  print(f'  enums: {len(state.ENUMS)}')
  print(f'  flags: {len(state.FLAGS)}')
  print(f'  structs: {len(state.STRUCTS)}')
  print(f'  objects: {len(state.OBJECTS)}')
  print(f'  global functions: {len(state.GLOBAL_FUNCTIONS)}')
  print(f'  callback functions: {len(state.CALLBACKS)}')


def generate(out_impl_path: Path, out_shared_path: Path):
  out_impl_path.parent.mkdir(parents=True, exist_ok=True)
  out_shared_path.parent.mkdir(parents=True, exist_ok=True)

  preamble: list[str] = [
    f'// GENERATED CODE - DO NOT MODIFY BY HAND',
    f'//',
    f'// Generated by tool/generate_dawn_bindings.py',
    f'//',
    f'// ignore_for_file: unused_element, unused_field, constant_identifier_names, prefer_function_declarations_over_variables, non_constant_identifier_names, unnecessary_cast, todo',
    f'//',
    f'// dart format off',
    f'',
    f'import \'dart:typed_data\';',
  ]

  shared_code = [
    *preamble,
    f'',
    f'import \'types/types.dart\';',
    f'',
    f'import \'chained_struct.dart\';',
    f'export \'chained_struct.dart\';',
    f'',
  ]

  impl_code = [
    *preamble,
    f'',
    f'import \'dart:io\';',
    f'import \'dart:async\';',
    f'import \'dart:ffi\' as ffi;',
    f'',
    f'import \'package:ffi/ffi.dart\';',
    f'',
    f'import \'package:webgpu/shared/webgpu.g.dart\';',
    f'import \'package:webgpu/webgpu.dart\' as webgpu;',
    f'import \'dawn_bindings.g.dart\' as bindings;',
    f'import \'platform.dart\';',
    f'',
    f'part \'dawn_impl.dart\';',
    f'part \'dawn_utils.dart\';',
    f'',
  ]

  def append_code(name: str, result: tuple[list[str], list[str]]):
    if name in SKIP_GENERATION: return
    if result[0]:
      shared_code.extend(result[0])
      shared_code.append('')
    if result[1]:
      impl_code.extend(result[1])
      impl_code.append('')

  for constant in state.CONSTANTS.values(): append_code(constant.name, generate_constant_code(constant))
  for enum in state.ENUMS.values(): append_code(enum.name, generate_enum_code(enum))
  for flag in state.FLAGS.values(): append_code(flag.name, generate_flag_code(flag))
  for struct in state.STRUCTS.values(): append_code(struct.name, generate_struct_code(struct))
  for obj in state.OBJECTS.values():
    skip_methods = []
    for method in SKIP_GENERATION:
      if method.startswith(f'{obj.name}.'): skip_methods.append(method.split('.', 1)[1])
    append_code(obj.name, generate_object_code(obj, skip_methods))
  for global_func in state.GLOBAL_FUNCTIONS.values(): append_code(global_func.name, generate_global_function_code(global_func))
  for callback in state.CALLBACKS.values(): append_code(callback.name, generate_callback_code(callback))

  impl_code.extend(generate_chained_struct_transformer())

  out_impl_path.write_text('\n'.join(impl_code))
  out_shared_path.write_text('\n'.join(shared_code))


if __name__ == '__main__':
  ap = ArgumentParser()
  ap.add_argument('--spec-path', type=Path, required=True)
  ap.add_argument('--out-impl', type=Path, required=True)
  ap.add_argument('--out-shared', type=Path, required=True)
  args = ap.parse_args()

  state.spec = json.loads(args.spec_path.read_text())

  parse()
  generate(args.out_impl, args.out_shared)
